// dbschema splits `pg_dump --schema-only` into one file per object: db/schema/<schema>/tables/<table>.sql (with the
// table's keys, indexes and identity sequence), .../functions/<name>.sql, .../views/<name>.sql, .../types/<name>.sql.
// `make schema` runs it on a database migrated from scratch.
//
//	dbschema -out db/schema < dump.sql          write the snapshot
//	dbschema -out db/schema -check < dump.sql   fail if the written snapshot differs
package main

import (
	"bufio"
	"bytes"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

const header = "-- Generated by make schema from db/migrations. Do not edit: write a migration instead.\n"

var (
	nameLine  = regexp.MustCompile(`^-- Name: (.+); Type: (.+); Schema: (.+); Owner: .*$`)
	tableRef  = regexp.MustCompile(`(?m)^ALTER TABLE (?:ONLY )?([a-z_]+)\.([a-z_]+)`)
	indexedOn = regexp.MustCompile(` ON (?:ONLY )?([a-z_]+)\.([a-z_]+) `)
)

func main() {
	out := flag.String("out", "db/schema", "snapshot directory")
	check := flag.Bool("check", false, "compare with the snapshot instead of writing it")
	flag.Parse()
	files, err := split(os.Stdin)
	if err == nil {
		if *check {
			err = compare(*out, files)
		} else {
			err = write(*out, files)
		}
	}

	if err != nil {
		fmt.Fprintln(os.Stderr, "dbschema:", err)
		os.Exit(1)
	}
}

// split reads the dump block by block; each block starts with a "-- Name: …; Type: …; Schema: …" comment.
func split(r io.Reader) (map[string]string, error) {
	files := map[string][]string{}
	var path string
	var body strings.Builder
	flush := func() {
		if dir, file := filepath.Split(path); strings.HasPrefix(file, "?") { // the statement named no table
			path = filepath.Join(filepath.Dir(filepath.Dir(dir)), "other.sql")
		}
		if text := strings.TrimSpace(body.String()); path != "" && text != "" {
			files[path] = append(files[path], text)
		}
		body.Reset()
	}
	sc := bufio.NewScanner(r)
	sc.Buffer(make([]byte, 1<<20), 1<<24)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, `\restrict`) || strings.HasPrefix(line, `\unrestrict`) || strings.HasPrefix(line, "-- PostgreSQL database dump complete") {
			continue
		}
		if line == "--" || strings.HasPrefix(line, "SET ") { // header frames and session settings
			continue
		}
		if m := nameLine.FindStringSubmatch(line); m != nil {
			flush()
			path = target(m[1], m[2], m[3])
			continue
		}
		if path == "" { // the preamble: SET statements
			continue
		}
		body.WriteString(line + "\n")
		if p, ok := refine(path, line); ok {
			path = p
		}
	}

	flush()
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("read dump: %w", err)
	}

	out := map[string]string{}
	for p, parts := range files {
		out[p] = header + "\n" + strings.Join(parts, "\n\n") + "\n"
	}

	return out, nil
}

// target is the file of an object by its header; sequences and indexes are moved to their table by refine.
func target(name, kind, schema string) string {
	if kind == "SCHEMA" {
		return filepath.Join(name, "schema.sql")
	}

	if schema == "-" || schema == "public" {
		return ""
	}

	table := func(t string) string { return filepath.Join(schema, "tables", t+".sql") }
	switch kind {
	case "TABLE":
		return table(name)
	case "CONSTRAINT", "FK CONSTRAINT", "DEFAULT", "TRIGGER":
		t, _, _ := strings.Cut(name, " ")
		return table(t)
	case "SEQUENCE", "INDEX":
		return filepath.Join(schema, "tables", "?"+name) // decided by the statement (refine)
	case "FUNCTION", "PROCEDURE":
		n, _, _ := strings.Cut(name, "(")
		return filepath.Join(schema, "functions", n+".sql")
	case "VIEW", "MATERIALIZED VIEW":
		return filepath.Join(schema, "views", name+".sql")
	case "TYPE", "DOMAIN":
		return filepath.Join(schema, "types", name+".sql")
	}

	return filepath.Join(schema, "other.sql")
}

// refine moves a sequence or an index to the file of the table its statement names.
func refine(path, line string) (string, bool) {
	if !strings.Contains(path, string(filepath.Separator)+"?") {
		return "", false
	}

	for _, re := range []*regexp.Regexp{tableRef, indexedOn} {
		if m := re.FindStringSubmatch(line); m != nil {
			return filepath.Join(m[1], "tables", m[2]+".sql"), true
		}
	}

	return "", false
}

func write(dir string, files map[string]string) error {
	if err := os.RemoveAll(dir); err != nil {
		return fmt.Errorf("clear %s: %w", dir, err)
	}

	for p, text := range files {
		full := filepath.Join(dir, p)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return fmt.Errorf("mkdir: %w", err)
		}
		if err := os.WriteFile(full, []byte(text), 0o644); err != nil {
			return fmt.Errorf("write %s: %w", p, err)
		}
	}

	fmt.Printf("wrote %d files to %s\n", len(files), dir)
	return nil
}

func compare(dir string, files map[string]string) error {
	var stale []string
	for p, text := range files {
		if b, err := os.ReadFile(filepath.Join(dir, p)); err != nil || !bytes.Equal(b, []byte(text)) {
			stale = append(stale, p)
		}
	}

	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, _ := filepath.Rel(dir, path)
		if _, ok := files[rel]; !ok {
			stale = append(stale, rel+" (no longer in the database)")
		}
		return nil
	})
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}

	if len(stale) > 0 {
		slices.Sort(stale)
		return fmt.Errorf("the snapshot is out of date, run make schema:\n  %s", strings.Join(stale, "\n  "))
	}

	fmt.Println("the snapshot matches the migrations")
	return nil
}
